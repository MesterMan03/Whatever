function lathe(name: string, radius: number, halfSegment: number): void {
  const segments = 24;
  const hemisphereRings = 8;
  const positions: number[][] = [];
  const normals: number[][] = [];
  const uvs: number[][] = [];
  for (const hemisphere of [-1, 1])
    for (let row = 0; row <= hemisphereRings; row++) {
      const phi =
        hemisphere < 0
          ? -Math.PI / 2 + ((row / hemisphereRings) * Math.PI) / 2
          : ((row / hemisphereRings) * Math.PI) / 2;
      for (let column = 0; column <= segments; column++) {
        const theta = (column / segments) * Math.PI * 2;
        const normal = [
          Math.cos(phi) * Math.cos(theta),
          Math.sin(phi),
          Math.cos(phi) * Math.sin(theta),
        ];
        positions.push([
          radius * normal[0],
          hemisphere * halfSegment + radius * normal[1],
          radius * normal[2],
        ]);
        normals.push(normal);
        uvs.push([
          column / segments,
          (positions.at(-1)![1] + halfSegment + radius) / (2 * (halfSegment + radius)),
        ]);
      }
    }
  const number = (n: number) => Number(n.toFixed(7));
  const output = [
    "# Generated by tools/generate-physics-demo.ts.",
    ...positions.map((p) => `v ${p.map(number).join(" ")}`),
    ...uvs.map((p) => `vt ${p.map(number).join(" ")}`),
    ...normals.map((p) => `vn ${p.map(number).join(" ")}`),
  ];
  const vertex = (i: number) => `${i}/${i}/${i}`;
  const rows = 2 * (hemisphereRings + 1);
  for (let row = 0; row < rows - 1; row++)
    for (let column = 0; column < segments; column++) {
      const a = row * (segments + 1) + column + 1;
      const b = a + segments + 1;
      const c = b + 1;
      const d = a + 1;
      for (const triangle of [
        [a, b, c],
        [a, c, d],
      ]) {
        const [p, q, r] = triangle.map((i) => positions[i - 1]);
        const u = q.map((value, i) => value - p[i]);
        const v = r.map((value, i) => value - p[i]);
        if (
          Math.hypot(
            u[1] * v[2] - u[2] * v[1],
            u[2] * v[0] - u[0] * v[2],
            u[0] * v[1] - u[1] * v[0],
          ) < 1e-9
        )
          continue;
        output.push(`f ${triangle.map(vertex).join(" ")}`);
      }
    }
  put(`meshes/${name}.obj`, output.join("\n"));
}
